test('예시 자동 업데이트 저장 실패 시 원본 유지와 수동 재시도', async ({ page }) => {
  const legacy = { ...emptyData(), rooms: addExamples([]).slice(0, 3).map(room => ({ ...room, builtYear: null })) };
  await page.evaluate(data => localStorage.setItem('bang-gijun:v1', JSON.stringify(data)), legacy);
  await page.addInitScript(() => {
    const original = Storage.prototype.setItem;
    Object.defineProperty(window, 'restoreStorage', { value: () => { Storage.prototype.setItem = original; } });
    Storage.prototype.setItem = () => { throw new DOMException('Quota exceeded', 'QuotaExceededError'); };
  });
  await page.reload();
  await expect(page.getByRole('alert')).toContainText('예시 업데이트: 저장하지 못했습니다');
  await expect(page.getByRole('article')).toHaveCount(3);
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('bang-gijun:v1')!))).toEqual(legacy);
  await page.evaluate(() => (window as unknown as { restoreStorage: () => void }).restoreStorage());
  await page.getByRole('button', { name: '예시 매물 불러오기' }).click();
  await expect(page.getByRole('article')).toHaveCount(6);
  await expect(card(page, '연희 C')).toContainText('2020년 준공');
  await expect(page.getByRole('alert')).toHaveCount(0);
});
